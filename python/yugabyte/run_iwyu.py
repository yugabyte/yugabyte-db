"""
Runs Include What You Use (IWYU) on YugabyteDB's C++ code.

This tool analyzes C++ source files in src/yb to check if the correct headers are included.
It uses the compilation database (compile_commands.json) generated by CMake.

Usage:
    ./yb_build.sh --iwyu
    # or directly:
    build-support/run_iwyu --build_root <build_root>
"""

import argparse
import fnmatch
import os
import logging
import multiprocessing
import random
import re
import subprocess

from typing import List, Optional

from overrides import overrides  # type: ignore

from yugabyte.common_util import YB_SRC_ROOT, init_logging
from yugabyte.tool_base import YbBuildToolBase
from yugabyte.compile_commands import (
    get_compile_commands_file_path,
    CompileCommand,
    COMBINED_POSTPROCESSED_DIR_NAME,
)
from yugabyte.json_util import read_json_file
from yugabyte.iwyu_runner import IWYURunner


def is_yb_source_file(rel_path: str) -> bool:
    """Check if the file is a YB source file (in src/yb directory)."""
    return rel_path.startswith('src/yb/')


def is_cpp_source_file(rel_path: str) -> bool:
    """Check if the file is a C++ translation unit."""
    return rel_path.endswith(('.cc', '.cpp', '.cxx'))


def is_generated_file(rel_path: str) -> bool:
    """Check if the file is auto-generated (protobuf, etc.)."""
    return rel_path.endswith((
        '.pb.cc',
        '.pb.h',
        '.messages.cc',
        '.messages.h',
        '.service.cc',
        '.service.h',
        '.proxy.cc',
        '.proxy.h',
    ))


class IWYUTool(YbBuildToolBase):
    """Tool for running Include What You Use on YugabyteDB C++ code."""

    def __init__(self) -> None:
        super().__init__()

    @overrides
    def add_command_line_args(self) -> None:
        self.arg_parser.add_argument(
            '--iwyu-path',
            help='Path to the include-what-you-use executable. If not specified, '
                 'will search in the toolchain and PATH.')

        self.arg_parser.add_argument(
            '--mapping-file',
            help='Path to IWYU mapping file (.imp). Default: yugabyte.imp in repo root.')

        self.arg_parser.add_argument(
            '--glob', '-g',
            help='Only process files matching this glob pattern (e.g., "*tablet*")')

        self.arg_parser.add_argument(
            '--regex', '-r',
            help='Only process files matching this regex pattern')

        self.arg_parser.add_argument(
            '--apply-fixes',
            action='store_true',
            help='Apply the suggested fixes using fix_includes.py (requires IWYU tools)')

        self.arg_parser.add_argument(
            '--include-generated',
            action='store_true',
            help='Include auto-generated files (protobuf, etc.) in the analysis')

        num_cpus = multiprocessing.cpu_count()
        self.arg_parser.add_argument(
            '--parallelism', '-j',
            type=int,
            default=num_cpus,
            help=f'Number of parallel IWYU processes. Default: {num_cpus}')

        self.arg_parser.add_argument(
            '--',
            dest='iwyu_extra_args',
            nargs=argparse.REMAINDER,
            help='Extra arguments to pass to IWYU (after --)')

    def find_iwyu_executable(self) -> str:
        """Find the IWYU executable."""
        if self.args.iwyu_path:
            if os.path.isfile(self.args.iwyu_path):
                return self.args.iwyu_path
            raise FileNotFoundError(f"IWYU not found at specified path: {self.args.iwyu_path}")

        # Try toolchain path
        toolchain_iwyu = os.path.join(self.args.build_root, 'toolchain', 'bin',
                                       'include-what-you-use')
        if os.path.isfile(toolchain_iwyu):
            return toolchain_iwyu

        # Try to find in PATH
        try:
            result = subprocess.run(['which', 'include-what-you-use'],
                                    capture_output=True, text=True)
            if result.returncode == 0:
                return result.stdout.strip()
        except Exception:
            pass

        try:
            result = subprocess.run(['which', 'iwyu'], capture_output=True, text=True)
            if result.returncode == 0:
                return result.stdout.strip()
        except Exception:
            pass

        raise FileNotFoundError(
            "Could not find include-what-you-use. Please install it or specify --iwyu-path")

    def get_mapping_file(self) -> Optional[str]:
        """Get the path to the IWYU mapping file."""
        if self.args.mapping_file:
            if os.path.isfile(self.args.mapping_file):
                return self.args.mapping_file
            logging.warning(f"Mapping file not found: {self.args.mapping_file}")
            return None

        # Try default location
        default_mapping = os.path.join(YB_SRC_ROOT, 'yugabyte.imp')
        if os.path.isfile(default_mapping):
            return default_mapping

        return None

    def load_and_filter_commands(self) -> List[CompileCommand]:
        """Load compilation commands and filter them."""
        compile_commands_path = get_compile_commands_file_path(
            self.args.build_root, COMBINED_POSTPROCESSED_DIR_NAME)

        if not os.path.exists(compile_commands_path):
            raise FileNotFoundError(
                f"Compilation database not found: {compile_commands_path}\n"
                "Please run a build first to generate compile_commands.json:\n"
                "  ./yb_build.sh --cmake-only")

        logging.info(f"Loading compilation database from {compile_commands_path}")
        compile_commands_json = read_json_file(compile_commands_path)

        commands: List[CompileCommand] = []
        for cmd_json in compile_commands_json:
            cmd = CompileCommand.from_json_obj(cmd_json)

            # Only include src/yb files
            if not is_yb_source_file(cmd.rel_file_path):
                continue

            # Never run IWYU on C translation units.
            if not is_cpp_source_file(cmd.rel_file_path):
                continue

            # Skip generated files unless explicitly requested
            if not self.args.include_generated and is_generated_file(cmd.rel_file_path):
                continue

            # Apply glob filter
            if self.args.glob:
                glob_pattern = f"*{self.args.glob}*"
                if not fnmatch.fnmatch(cmd.rel_file_path, glob_pattern):
                    continue

            # Apply regex filter
            if self.args.regex:
                if not re.search(self.args.regex, cmd.rel_file_path):
                    continue

            commands.append(cmd)

        logging.info(f"Found {len(commands)} files to analyze")
        return commands

    @overrides
    def run_impl(self) -> None:
        iwyu_path = self.find_iwyu_executable()
        logging.info(f"Using IWYU: {iwyu_path}")

        mapping_file = self.get_mapping_file()
        if mapping_file:
            logging.info(f"Using mapping file: {mapping_file}")

        commands = self.load_and_filter_commands()
        if not commands:
            logging.warning("No files to analyze")
            return

        # Shuffle for better load balancing
        random.shuffle(commands)

        # Get extra args
        extra_args = getattr(self.args, 'iwyu_extra_args', None) or []
        if extra_args and extra_args[0] == '--':
            extra_args = extra_args[1:]

        compile_commands_path = get_compile_commands_file_path(
            self.args.build_root, COMBINED_POSTPROCESSED_DIR_NAME)

        runner = IWYURunner(
            parallelism=self.args.parallelism,
            iwyu_path=iwyu_path,
            compile_commands_path=compile_commands_path,
            extra_args=extra_args,
            mapping_file=mapping_file,
            verbose=self.args.verbose)

        logging.info(f"Running IWYU on {len(commands)} files with parallelism {self.args.parallelism}")
        runner.run_tasks(commands)

        if self.args.apply_fixes:
            logging.info("Fix application requested but not yet implemented. "
                         "Use the IWYU output to manually apply fixes or use iwyu-fix-includes.")


def main() -> None:
    tool = IWYUTool()
    tool.run()


if __name__ == '__main__':
    main()
